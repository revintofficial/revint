type _Raw = typeof common;
type Widen<T> = T extends string
  ? string
  : T extends ReadonlyArray<infer U>
    ? ReadonlyArray<Widen<U>>
    : T extends object
      ? { readonly [K in keyof T]: Widen<T[K]> }
      : T;

export type CommonDictionary = Widen<_Raw>;
